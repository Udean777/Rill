import AppKit
import os
import RillDomain

/// Periodically observes `NSPasteboard.general` changeCount, filters sensitive
/// content, extracts rich payloads, and dispatches them to domain storage.
@MainActor
public final class PasteboardWatcher {
    private let log = Logger(subsystem: "com.ssajudn.Rill", category: "pasteboardWatcher")
    private let pasteboard = NSPasteboard.general
    private let imagesDirectoryURL: URL
    private let onItemCopied: (RawClipboardEntry) async -> Void

    private var lastChangeCount: Int
    private var isRunning = false
    private var pollingTask: Task<Void, Never>?

    // Transient & concealed types from password managers and self-paste operations
    private static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let onePasswordType = NSPasteboard.PasteboardType("com.agilebits.onepassword")

    public init(
        imagesDirectoryURL: URL,
        onItemCopied: @escaping (RawClipboardEntry) async -> Void
    ) {
        self.imagesDirectoryURL = imagesDirectoryURL
        self.onItemCopied = onItemCopied
        self.lastChangeCount = pasteboard.changeCount
    }

    public func start() {
        guard !isRunning else { return }
        isRunning = true
        lastChangeCount = pasteboard.changeCount

        pollingTask = Task { [weak self] in
            while !Task.isCancelled {
                try? await Task.sleep(for: .milliseconds(300))
                guard !Task.isCancelled, let self else { break }
                self.checkPasteboard()
            }
        }
    }

    public func stop() {
        isRunning = false
        pollingTask?.cancel()
        pollingTask = nil
    }

    /// Called by writer before writing self-paste content so the watcher ignores it.
    public func ignoreNextChange(count: Int) {
        lastChangeCount = count
    }

    private func checkPasteboard() {
        let currentCount = pasteboard.changeCount
        guard currentCount != lastChangeCount else { return }
        lastChangeCount = currentCount

        // Guard sensitive & transient types
        let types = pasteboard.types ?? []
        if types.contains(Self.concealedType) ||
           types.contains(Self.autoGeneratedType) ||
           types.contains(Self.transientType) ||
           types.contains(Self.onePasswordType) {
            log.debug("ignoring sensitive or transient pasteboard entry")
            return
        }

        // Identify originating application
        let frontApp = NSWorkspace.shared.frontmostApplication
        let sourceApp: ClipboardSourceApp?
        if let frontApp, frontApp.bundleIdentifier != Bundle.main.bundleIdentifier {
            sourceApp = ClipboardSourceApp(
                name: frontApp.localizedName ?? "App",
                bundleID: frontApp.bundleIdentifier ?? ""
            )
        } else {
            sourceApp = nil
        }

        // 1. Files
        if let fileURLs = pasteboard.readObjects(forClasses: [NSURL.self], options: nil) as? [URL],
           !fileURLs.isEmpty {
            let pathStrings = fileURLs.map(\.path)
            let entry = RawClipboardEntry(
                fileURLs: pathStrings,
                sourceApp: sourceApp,
                copiedAt: Date()
            )
            Task { [weak self] in
                await self?.onItemCopied(entry)
            }
            return
        }

        // 2. Images
        if let image = NSImage(pasteboard: pasteboard),
           let tiffData = image.tiffRepresentation,
           let bitmap = NSBitmapImageRep(data: tiffData),
           let pngData = bitmap.representation(using: .png, properties: [:]) {
            let fileName = "\(UUID().uuidString).png"
            let targetURL = imagesDirectoryURL.appendingPathComponent(fileName)

            do {
                if !FileManager.default.fileExists(atPath: imagesDirectoryURL.path) {
                    try FileManager.default.createDirectory(at: imagesDirectoryURL, withIntermediateDirectories: true)
                }
                try pngData.write(to: targetURL, options: .atomic)

                let dimensions = ImageDimensions(
                    width: Int(image.size.width),
                    height: Int(image.size.height)
                )
                let entry = RawClipboardEntry(
                    imageFileName: fileName,
                    imageDimensions: dimensions,
                    byteSize: pngData.count,
                    sourceApp: sourceApp,
                    copiedAt: Date()
                )
                Task { [weak self] in
                    await self?.onItemCopied(entry)
                }
                return
            } catch {
                log.error("failed to save clipboard image: \(String(describing: error), privacy: .public)")
            }
        }

        // 3. Text & Rich Text
        if let string = pasteboard.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let rtfString = pasteboard.string(forType: .rtf)
            let entry = RawClipboardEntry(
                textContent: string,
                richTextContent: rtfString,
                byteSize: string.utf8.count,
                sourceApp: sourceApp,
                copiedAt: Date()
            )
            Task { [weak self] in
                await self?.onItemCopied(entry)
            }
        }
    }
}
